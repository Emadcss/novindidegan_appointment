/** آخرین نسخه ساختار دیتابیس */
export const LATEST_SCHEMA_VERSION = MIGRATIONS.length;

/**
 * ساخت جدول تاریخچه و اجرای مهاجرت‌های اجرا نشده.
 *
 * این تابع داخل تراکنش bootstrap فراخوانی می‌شود؛
 * بنابراین خطای یک مهاجرت باعث rollback تراکنش خواهد شد.
 */
export async function runMigrations(exec: Exec): Promise<void> {
    await exec(`
        CREATE TABLE IF NOT EXISTS schema_migrations (
                                                         version INTEGER PRIMARY KEY,
                                                         applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
    `);

    const rows = await exec(
        "SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations",
    );

    const current = Number(rows[0]?.v ?? 0);

    if (!Number.isInteger(current) || current < 0) {
        throw new Error("نسخه ثبت‌شده دیتابیس معتبر نیست.");
    }

    if (current > MIGRATIONS.length) {
        throw new Error(
            `نسخه دیتابیس (${current}) از نسخه پشتیبانی‌شده برنامه (${MIGRATIONS.length}) جدیدتر است.`,
        );
    }

    for (let version = current; version < MIGRATIONS.length; version += 1) {
        await exec(MIGRATIONS[version]);

        await exec(
            "INSERT INTO schema_migrations (version) VALUES ($1)",
            [version + 1],
        );
    }
}
