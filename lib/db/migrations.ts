import type { Exec } from "@/lib/db/connection";

/**
 * مهاجرت‌های دیتابیس PostgreSQL. هر عضو آرایه یک نسخه است و به ترتیب اجرا می‌شود.
 * ⚠ مهاجرت‌های قبلی را هرگز ویرایش نکنید؛ تغییر جدید = عضو تازه در انتهای آرایه.
 * نسخه‌های اجراشده در جدول schema_migrations ثبت می‌شوند.
 */
const MIGRATIONS: string[] = [
    // ---- نسخه ۱: ساختار اولیه ----
    `
    CREATE TABLE specialties (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        slug TEXT NOT NULL UNIQUE,
        icon TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        sort_order INTEGER NOT NULL DEFAULT 0
    );

    CREATE TABLE doctors (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        specialty_id INTEGER NOT NULL REFERENCES specialties(id),
        first_name TEXT NOT NULL,
        last_name TEXT NOT NULL,
        display_name TEXT NOT NULL,
        requires_surgery_history BOOLEAN NOT NULL DEFAULT FALSE,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        sort_order INTEGER NOT NULL DEFAULT 0
    );

    CREATE TABLE doctor_schedules (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        doctor_id INTEGER NOT NULL REFERENCES doctors(id),
        weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
        start_time TIME NOT NULL,
        end_time TIME NOT NULL,
        valid_from DATE NOT NULL,
        valid_until DATE,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        CHECK (end_time > start_time)
    );
    CREATE INDEX idx_schedules_doctor_weekday ON doctor_schedules (doctor_id, weekday);

    CREATE TABLE schedule_exceptions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        doctor_id INTEGER NOT NULL REFERENCES doctors(id),
        date DATE NOT NULL,
        type TEXT NOT NULL CHECK (type IN ('disabled', 'override')),
        start_time TIME,
        end_time TIME,
        reason TEXT,
        is_active BOOLEAN NOT NULL DEFAULT TRUE
    );
    -- حداکثر یک استثنای فعال برای هر پزشک در هر روز
    CREATE UNIQUE INDEX one_active_exception_per_day
        ON schedule_exceptions (doctor_id, date) WHERE is_active;

    CREATE TABLE patients (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nationality TEXT NOT NULL CHECK (nationality IN ('iranian', 'foreign')),
        national_id_hash TEXT UNIQUE,
        national_id_enc TEXT,
        mobile_hash TEXT UNIQUE,
        mobile_enc TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE appointments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        patient_id INTEGER NOT NULL REFERENCES patients(id),
        specialty_id INTEGER NOT NULL REFERENCES specialties(id),
        doctor_id INTEGER NOT NULL REFERENCES doctors(id),
        appointment_date DATE NOT NULL,
        appointment_time TIME NOT NULL,
        appointment_number INTEGER NOT NULL,
        has_surgery_history BOOLEAN,
        status TEXT NOT NULL DEFAULT 'booked'
            CHECK (status IN ('booked', 'completed', 'cancelled', 'no_show')),
        request_id TEXT UNIQUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        UNIQUE (specialty_id, doctor_id, appointment_date, appointment_number)
    );
    CREATE INDEX idx_appointments_patient_day
        ON appointments (patient_id, appointment_date);
    -- هر بیمار در هر روز برای هر پزشک حداکثر یک نوبت فعال دارد (پشتوانه‌ی قفل برنامه)
    CREATE UNIQUE INDEX one_active_per_doctor_day
        ON appointments (patient_id, doctor_id, appointment_date) WHERE status = 'booked';

    CREATE TABLE daily_counters (
        specialty_id INTEGER NOT NULL,
        doctor_id INTEGER NOT NULL,
        day DATE NOT NULL,
        last_number INTEGER NOT NULL DEFAULT 0,
        PRIMARY KEY (specialty_id, doctor_id, day)
    );

    // ---- نسخه ۲: ادمین + کیوسک‌ها ----
  
    CREATE TABLE admin_users (
                                 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 username TEXT NOT NULL UNIQUE,
                                 password_hash TEXT NOT NULL,
                                 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE kiosks (
                            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code TEXT NOT NULL UNIQUE,
                            name TEXT NOT NULL,
                            ip_address TEXT,
                            port INTEGER DEFAULT 3000,
                            location_note TEXT,
                            is_active BOOLEAN NOT NULL DEFAULT TRUE,
                            last_seen_at TIMESTAMPTZ,
                            last_error TEXT,
                            printer_status TEXT NOT NULL DEFAULT 'unknown'
                                CHECK (printer_status IN ('ok', 'paper_low', 'offline', 'unknown')),
                            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE INDEX idx_kiosks_last_seen ON kiosks (last_seen_at);

    CREATE TABLE IF NOT EXISTS admin_users (
                                               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               username TEXT NOT NULL UNIQUE,
                                               password_hash TEXT NOT NULL,
                                               created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
    `,
];



/** آخرین نسخه‌ی ساختار (برای خودآزمایی) */
export const LATEST_SCHEMA_VERSION = MIGRATIONS.length;

export async function runMigrations(exec: Exec): Promise<void> {
    await exec(
        `CREATE TABLE IF NOT EXISTS schema_migrations (
            version INTEGER PRIMARY KEY,
            applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )`,
    );

    const rows = await exec(
        "SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations",
    );
    const current = Number(rows[0]?.v ?? 0);

    for (let version = current; version < MIGRATIONS.length; version += 1) {
        await exec(MIGRATIONS[version]);
        await exec("INSERT INTO schema_migrations (version) VALUES ($1)", [
            version + 1,
        ]);
    }
}
